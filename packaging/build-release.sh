#!/bin/bash
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
output="${1:-$repo/build/release}"
mkdir -p "$output"
output="$(cd "$output" && pwd)"
derived="${STATS_DERIVED_DATA:-$repo/build/DerivedData}"
if [[ -z "${DEVELOPER_DIR:-}" && -d /Applications/Xcode.app/Contents/Developer ]]; then
    export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
fi
if [[ "$(uname -m)" != arm64 ]]; then
    echo "This release script builds the Apple Silicon edition. Run it on an Apple Silicon Mac." >&2
    exit 1
fi

/usr/bin/xcodebuild -project "$repo/Stats.xcodeproj" -scheme Stats -configuration Release \
    -destination 'platform=macOS,arch=arm64' -derivedDataPath "$derived" -jobs "${STATS_BUILD_JOBS:-7}" \
    CODE_SIGNING_ALLOWED=NO MACOSX_DEPLOYMENT_TARGET=14.0 ARCHS=arm64

staging="$(mktemp -d "$output/.package.XXXXXX")"
trap '/bin/rm -rf "$staging"' EXIT
app="$staging/Stats.app"
plugin="$app/Contents/PlugIns/WidgetsExtension.appex"
ditto "$derived/Build/Products/Release/Stats.app" "$app"

# The artwork is generated by the upstream v3.1.1 release using Icon Composer.
ditto "$repo/packaging/artwork" "$app/Contents/Resources"
cp "$repo/LICENSE" "$app/Contents/Resources/Stats-LICENSE.txt"
app_info="$app/Contents/Info.plist"
/usr/libexec/PlistBuddy -c 'Set :CFBundleName Stats' "$app_info"
/usr/libexec/PlistBuddy -c 'Set :CFBundleIconFile Stats' "$app_info" 2>/dev/null ||
    /usr/libexec/PlistBuddy -c 'Add :CFBundleIconFile string Stats' "$app_info"
/usr/libexec/PlistBuddy -c 'Set :CFBundleIconName Stats' "$app_info" 2>/dev/null ||
    /usr/libexec/PlistBuddy -c 'Add :CFBundleIconName string Stats' "$app_info"

while IFS= read -r -d '' framework; do
    /usr/bin/codesign --force --sign - "$framework"
done < <(/usr/bin/find "$app/Contents" -depth -type d -name '*.framework' -print0)
login="$app/Contents/Library/LoginItems/LaunchAtLogin.app"
if [[ -d "$login" ]]; then /usr/bin/codesign --force --sign - "$login"; fi
helpers="$app/Contents/Library/LaunchServices"
if [[ -d "$helpers" ]]; then
    /usr/bin/find "$helpers" -maxdepth 1 -type f -exec /usr/bin/codesign --force --sign - {} \;
fi
/usr/bin/codesign --force --sign - --entitlements "$repo/packaging/widgets.entitlements" "$plugin"
/usr/bin/codesign --force --sign - "$app"
/usr/bin/codesign --verify --deep --strict "$app"

for key in CFBundleShortVersionString CFBundleVersion; do
    host_version="$(/usr/libexec/PlistBuddy -c "Print :$key" "$app_info")"
    widget_version="$(/usr/libexec/PlistBuddy -c "Print :$key" "$plugin/Contents/Info.plist")"
    [[ "$host_version" == "$widget_version" ]]
done

asset="StatsWork-v0.1.0-macos-arm64.zip"
ditto -c -k --keepParent "$app" "$staging/$asset"
mv -f "$staging/$asset" "$output/$asset"
(cd "$output" && /usr/bin/shasum -a 256 "$asset" > "$asset.sha256")
printf 'Created %s/%s\n' "$output" "$asset"
